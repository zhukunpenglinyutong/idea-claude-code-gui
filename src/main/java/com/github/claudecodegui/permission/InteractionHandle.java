package com.github.claudecodegui.permission;

import com.google.gson.JsonObject;

import java.util.concurrent.atomic.AtomicBoolean;

/**
 * One resolvable permission / AskUserQuestion / Plan-Approval interaction,
 * shared between the desktop dialog path and the Remote gateway.
 *
 * <p>The handle is the single first-wins authority for completing the
 * underlying {@code CompletableFuture} that {@link PermissionService#dispatch*}
 * awaits. Every completion path &mdash; desktop JS decision, Remote HTTP
 * decision, safety-net timeout, and {@code clearPendingRequests} / abort cancel
 * &mdash; routes through {@link #tryComplete} / {@link #cancel}, whose
 * {@link AtomicBoolean} CAS guarantees exactly one winner (Phase 2C-C §5).
 *
 * <p>Identity:
 * <ul>
 *   <li>{@code (sessionId, requestId)} is the daemon-side identity and the
 *       registry key. {@code requestId} is only session-scoped unique, so
 *       {@code sessionId} always accompanies it.</li>
 *   <li>{@code channelId} is the desktop-only permission dialog channel (a UUID
 *       generated by {@code PermissionHandler.showFrontendPermissionDialog}). It
 *       is never exposed to Remote clients; the desktop JS decision path uses it
 *       to look the handle up. Null for AskUserQuestion / Plan (those use
 *       {@code requestId} on both sides).</li>
 * </ul>
 *
 * <p>Remote source metadata ({@code sourceProjectId/TabId/TaskId}) is attached
 * by the Remote interaction observer after the handle is registered, so the
 * Remote endpoint can validate that a decision targets the same project/tab/task
 * that originated the request (Phase 2C-C §7, §11 stale protection).
 *
 * <p>The {@link Completer} SPI keeps this class free of JCEF / handler-package
 * dependencies: {@code PermissionHandler} supplies the completer that knows how
 * to finish its typed future and force-close the frontend dialog.
 */
public final class InteractionHandle {

    /** Interaction kind. Mirrors {@code RemoteInteraction.Type} but lives in the permission package. */
    public enum Type { PERMISSION, QUESTION, PLAN }

    /**
     * Strategy for finishing the underlying future + frontend dialog. Implemented
     * by {@code PermissionHandler} (which owns the typed future and the
     * {@code forceCloseFrontendDialog} helper). The handle's CAS already
     * serialized the call, so {@code complete}/{@code cancel} run at most once.
     */
    public interface Completer {
        /** Complete the future with a decision value (int for permission, JsonObject for ask/plan). */
        void complete(Object value);

        /** Complete the future with the type-specific default (deny / null / reject) + close the dialog. */
        void cancel(String reason);
    }

    private final Type type;
    private final String sessionId;
    private final String requestId;
    private final String channelId;
    private final Completer completer;
    private final AtomicBoolean resolved = new AtomicBoolean(false);
    private final long createdAt;

    // Remote source metadata — attached after registration by the observer.
    private volatile String sourceProjectId;
    private volatile String sourceTabId;
    private volatile String sourceTaskId;
    // Original request payloads, for Remote answer/plan validation.
    private volatile JsonObject questionsData;
    private volatile JsonObject planData;

    public InteractionHandle(Type type, String sessionId, String requestId,
                             String channelId, Completer completer) {
        this.type = type;
        this.sessionId = sessionId;
        this.requestId = requestId;
        this.channelId = channelId;
        this.completer = completer;
        this.createdAt = System.currentTimeMillis();
    }

    public Type getType() { return type; }
    public String getSessionId() { return sessionId; }
    public String getRequestId() { return requestId; }
    public String getChannelId() { return channelId; }
    public long getCreatedAt() { return createdAt; }
    public boolean isResolved() { return resolved.get(); }

    public String getSourceProjectId() { return sourceProjectId; }
    public String getSourceTabId() { return sourceTabId; }
    public String getSourceTaskId() { return sourceTaskId; }
    public JsonObject getQuestionsData() { return questionsData; }
    public JsonObject getPlanData() { return planData; }

    public void attachSource(String projectId, String tabId, String taskId) {
        this.sourceProjectId = projectId;
        this.sourceTabId = tabId;
        this.sourceTaskId = taskId;
    }

    public void attachQuestions(JsonObject questions) { this.questionsData = questions; }
    public void attachPlan(JsonObject plan) { this.planData = plan; }

    /**
     * First-wins completion. Returns true if this call won the CAS and actually
     * completed the future; false if the interaction was already resolved.
     */
    boolean tryComplete(Object value) {
        if (resolved.compareAndSet(false, true)) {
            completer.complete(value);
            return true;
        }
        return false;
    }

    /**
     * First-wins cancellation (deny / null / reject). Returns true if this call
     * won; false if already resolved. Public so the owning handler
     * ({@code PermissionHandler}, in a different package) can drive safety-net
     * timeouts and show-error cleanups through the same first-wins gate.
     */
    public boolean cancel(String reason) {
        if (resolved.compareAndSet(false, true)) {
            completer.cancel(reason);
            return true;
        }
        return false;
    }

    /**
     * Validate that the resolver caller's (projectId, tabId, taskId) matches the
     * source that originated this interaction. Used by the Remote endpoint to
     * reject stale / cross-task / cross-tab decisions.
     */
    boolean matchesSource(String projectId, String tabId, String taskId) {
        return eq(sourceProjectId, projectId)
                && eq(sourceTabId, tabId)
                && eq(sourceTaskId, taskId);
    }

    private static boolean eq(String a, String b) {
        return a != null ? a.equals(b) : b == null;
    }
}
